"""Regenerate the README speed table from external benchmark records.

The benchmark records are intentionally supplied as arguments rather than
stored in the repository.  This keeps machine-specific timings out of source
control while making the published table reproducible when a new build is
available.

Example::

    python tools/update_readme_speed_table.py \
        --record cpu=/path/to/cpu-5000.json \
        --record cuda=/path/to/cuda-5000.json
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
from typing import Any


BEGIN = "<!-- BEGIN GENERATED SPEED TABLE -->"
END = "<!-- END GENERATED SPEED TABLE -->"
WATER_BEGIN = "<!-- BEGIN GENERATED WATER SPEED TABLE -->"
WATER_END = "<!-- END GENERATED WATER SPEED TABLE -->"


def _record_metric(record: dict[str, Any]) -> float:
    candidates = (
        record.get("median_us_per_atom"),
        record.get("median_us_per_atom_step"),
        (record.get("timing") or {}).get("median_us_per_atom"),
    )
    for value in candidates:
        if isinstance(value, (int, float)) and value > 0:
            return float(value)
    raise ValueError("record has no positive median_us_per_atom value")


def _record_atoms(record: dict[str, Any]) -> int:
    candidates = (
        record.get("atoms"),
        record.get("atom_count"),
        (record.get("graph") or {}).get("atom_count"),
    )
    for value in candidates:
        if isinstance(value, int) and value > 0:
            return value
    raise ValueError("record has no positive atom count")


def _display_model(record: dict[str, Any]) -> str:
    value = record.get("model_name") or record.get("model") or "unknown"
    return Path(str(value)).name or str(value)


def _display_backend(record: dict[str, Any], fallback: str) -> str:
    value = record.get("backend")
    if isinstance(value, dict):
        value = value.get("backend") or value.get("selector")
    return str(value or fallback)


def _display_hardware(record: dict[str, Any]) -> str:
    for key in ("hardware", "device_name", "gpu_name", "cpu_name"):
        value = record.get(key)
        if value:
            return str(value)
    device = record.get("device")
    if isinstance(device, dict):
        for key in ("name", "model"):
            if device.get(key):
                return str(device[key])
    return "not recorded"


def _display_timing_boundary(record: dict[str, Any]) -> str:
    return str(record.get("timing_boundary") or "not recorded")


def _parse_record_argument(value: str) -> tuple[str, Path]:
    label, separator, filename = value.partition("=")
    if not separator or not label or not filename:
        raise argparse.ArgumentTypeError("record must be LABEL=JSON_PATH")
    return label, Path(filename)


def render_table(
    records: list[tuple[str, dict[str, Any]]],
    *,
    atoms: int,
    begin: str = BEGIN,
    end: str = END,
    footer: str | None = None,
) -> str:
    rows: list[tuple[str, str, str, str, float, str]] = []
    for label, record in records:
        status = record.get("status")
        if status not in (None, "ok", "passed"):
            raise ValueError(f"{label}: record status is not passing: {status!r}")
        observed_atoms = _record_atoms(record)
        if observed_atoms != atoms:
            raise ValueError(f"{label}: expected {atoms} atoms, found {observed_atoms}")
        backend = _display_backend(record, label)
        rows.append(
            (
                backend,
                _display_model(record),
                _display_hardware(record),
                _display_timing_boundary(record),
                _record_metric(record),
                label,
            )
        )
    rows.sort(key=lambda row: (row[0], row[1], row[3]))
    lines = [
        begin,
        "<!-- Generated by tools/update_readme_speed_table.py. -->",
        "<!-- Records are external benchmark outputs and are not committed. -->",
        "",
        "| Backend | Model | Hardware | Timing boundary | Median µs/atom | Median atoms/s |",
        "|---|---|---|---|---:|---:|",
    ]
    lines.extend(
        f"| {backend} | {model} | {hardware} | {boundary} | {metric:.3f} | {1_000_000.0 / metric:,.0f} |"
        for backend, model, hardware, boundary, metric, _label in rows
    )
    lines.extend(
        [
            "",
            *(
                [footer]
                if footer is not None
                else [
                    f"The canonical comparison workload is a {atoms:,}-atom cubic SrTiO₃",
                    "energy–forces–stress evaluation; see the paper for the full protocol.",
                ]
            ),
            end,
        ]
    )
    return "\n".join(lines)


def update_readme(
    readme: Path, table: str, *, begin: str = BEGIN, end: str = END
) -> None:
    text = readme.read_text(encoding="utf-8")
    pattern = re.compile(rf"{re.escape(begin)}.*?{re.escape(end)}", re.DOTALL)
    if not pattern.search(text):
        raise ValueError(f"README is missing generated-table markers: {readme}")
    readme.write_text(pattern.sub(table, text, count=1), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--readme", type=Path, default=Path("README.md"))
    parser.add_argument("--atoms", type=int, default=5000)
    parser.add_argument("--marker", choices=("speed", "water"), default="speed")
    parser.add_argument(
        "--record",
        action="append",
        type=_parse_record_argument,
        required=True,
        metavar="LABEL=JSON_PATH",
    )
    args = parser.parse_args(argv)
    if args.atoms <= 0:
        parser.error("--atoms must be positive")
    records = []
    for label, path in args.record:
        record = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(record, dict):
            raise ValueError(f"{path}: top-level JSON value must be an object")
        records.append((label, record))
    if args.marker == "water":
        begin, end = WATER_BEGIN, WATER_END
        footer = (
            "These rows use the deterministic periodic 1,000-water cell "
            "(3,000 atoms); timing boundaries are stated per row."
        )
    else:
        begin, end, footer = BEGIN, END, None
    update_readme(
        args.readme,
        render_table(records, atoms=args.atoms, begin=begin, end=end, footer=footer),
        begin=begin,
        end=end,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
